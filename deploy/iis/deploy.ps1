<#
  Builds smt-ui once and deploys it to every IIS folder in targets.json.
  Each folder gets its own runtime-config.js with that target's API URL.

  Usage (from smt-ui/):
    npm run deploy                      # build + deploy to all targets
    npm run deploy -- -Only smt-frontend
    npm run deploy -- -SkipBuild        # redeploy the existing build/ folder
#>
param(
  [string[]]$Only,
  [switch]$SkipBuild,
  [string]$TargetsFile = (Join-Path $PSScriptRoot 'targets.json')
)

$ErrorActionPreference = 'Stop'
$root    = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$build   = Join-Path $root 'build'
$targets = Get-Content $TargetsFile -Raw | ConvertFrom-Json
if ($Only) { $targets = $targets | Where-Object { $Only -contains $_.name } }
if (-not $targets) { throw "No matching targets in targets.json" }

if (-not $SkipBuild) {
  Push-Location $root
  try {
    npm run build
    if ($LASTEXITCODE -ne 0) { throw "npm run build failed ($LASTEXITCODE)" }
  } finally { Pop-Location }
}
if (-not (Test-Path (Join-Path $build 'index.html'))) { throw "No build found at $build" }

foreach ($t in $targets) {
  Write-Host "==> $($t.name) -> $($t.path)" -ForegroundColor Cyan
  if (-not (Test-Path $t.path)) { New-Item -ItemType Directory -Path $t.path | Out-Null }

  # /MIR also removes old main.*.js bundles left by earlier deploys.
  robocopy $build $t.path /MIR /NFL /NDL /NJH /NP | Out-Host
  if ($LASTEXITCODE -ge 8) { throw "robocopy failed for $($t.name) ($LASTEXITCODE)" }

  $cfg = [ordered]@{ apiUrl = $t.apiUrl; fileUrl = $t.fileUrl } | ConvertTo-Json -Compress
  $js  = "// Generated by deploy/iis/deploy.ps1 for $($t.name)`nwindow.__SMT_CONFIG__ = $cfg;`n"
  [IO.File]::WriteAllText((Join-Path $t.path 'runtime-config.js'), $js, (New-Object Text.UTF8Encoding $false))
  Write-Host "    api: $($t.apiUrl)" -ForegroundColor Green
}
$global:LASTEXITCODE = 0
Write-Host "Done." -ForegroundColor Green
